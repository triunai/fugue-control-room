using Fugue.Domain.Customers;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Fugue.Infrastructure.Persistence.Configurations;

internal sealed class CustomerConfiguration : IEntityTypeConfiguration<Customer>
{
    public void Configure(EntityTypeBuilder<Customer> builder)
    {
        builder.ToTable("customers");
        builder.HasKey(c => c.Id);
        builder.Property(c => c.Id).ValueGeneratedNever(); // ids are UUIDv7 generated by the domain

        builder.Property(c => c.Name).HasMaxLength(200).IsRequired();
        builder.Property(c => c.Email).HasMaxLength(254).IsRequired();
        builder.Property(c => c.Phone).HasMaxLength(16);
        builder.Property(c => c.Status).HasConversion<string>().HasMaxLength(16).IsRequired();

        builder.Property(c => c.CreatedBy).HasMaxLength(64).IsRequired();
        builder.Property(c => c.UpdatedBy).HasMaxLength(64).IsRequired();

        // Postgres xmin as the optimistic-concurrency token (ADR-006): the ETag / If-Match version.
        builder.Property(c => c.RowVersion)
            .HasColumnName("xmin")
            .HasColumnType("xid")
            .IsRowVersion(); // Npgsql: system column, never created by migrations

        builder.HasIndex(c => c.Email).IsUnique().HasDatabaseName("ux_customers_email");
        builder.HasIndex(c => new { c.CreatedAt, c.Id }).HasDatabaseName("ix_customers_created_at_id"); // keyset paging
    }
}
