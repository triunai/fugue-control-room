import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import path from "node:path";
import { idsIn, canon, refIds, slug, parseBoard, parseLog, parseDecisions, parseAdr, parseGitLog, generate, OUT } from "./trace-index.mjs";

test("ids: canonical form, ranges, sorted", () => {
  assert.equal(canon("D-21"), "D-021");
  assert.deepEqual(idsIn("D-016..D-018, ADR-008, W-5"), ["ADR-008", "D-016", "D-017", "D-018", "W-005"]);
  assert.deepEqual(refIds("W-012, ADR-010; D-22.\nW-012"), ["W-012", "ADR-010", "D-022"]);
});
test("slug follows GitHub anchors", () => assert.equal(slug("2026-11-25 — Closed W-005: S3, JWT"), "2026-11-25--closed-w-005-s3-jwt"));
test("board, log, decisions and adr parsers", () => {
  const b = parseBoard("### WS-06 — S4 outbox — ⏸ PARKED (2026-11-25)\nID: W-006\nStatus: x\n");
  assert.deepEqual([b[0].id, b[0].title, b[0].status], ["W-006", "S4 outbox", "PARKED"]);
  const l = parseLog("# h\n\n## 2026-11-25 — Closed W-009: Map\nWS: WS-09\nClosed: W-009 (WS-09) Map\nCommits:\n- 4e8ee4e feat x\nDecisions: D-009, ADR-004\n");
  assert.deepEqual([l[0].closed, l[0].shas, l[0].ids], ["W-009", ["4e8ee4e"], ["ADR-004", "D-009"]]);
  const d = parseDecisions("| D-004 | t | [ADR-006](adr/x.md) |\n\n## D-004 — EF reads — 2026-11-25\nWS: WS-02\nStatus: accepted\nPromote: yes (ADR-006)\n");
  assert.deepEqual([d[0].id, d[0].adrs, d[0].ws], ["D-004", ["ADR-006"], ["W-002"]]);
  assert.deepEqual(parseAdr("ADR-006-x.md", "# ADR-006: EF Core\n- Status: Accepted\n"), { id: "ADR-006", file: "ADR-006-x.md", title: "EF Core", status: "Accepted" });
  const g = parseGitLog("\x1eaaa111\x1fa1\x1f2026-01-01\x1fsubj | x\x1fW-1,ADR-6\nA\tdocs/adr/ADR-006-x.md\n");
  assert.deepEqual([g[0].sha, g[0].refs, g[0].files[0].status], ["a1", ["W-001", "ADR-006"], "A"]);
});

function repo() {
  const root = mkdtempSync(path.join(tmpdir(), "trace-"));
  const git = (...a) => execFileSync("git", a, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  const w = (p, t) => { mkdirSync(path.dirname(path.join(root, p)), { recursive: true }); writeFileSync(path.join(root, p), t); };
  const commit = (msg, ...paths) => { git("add", ...paths); git("-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "-m", msg, "--", ...paths); };
  git("init", "-q");
  return { root, w, commit, git };
}

test("generates links both ways and is idempotent; a trace-only commit is invisible", () => {
  const { root, w, commit } = repo();
  w("docs/workstreams.md", "### WS-01 — Thing — 🟢 ACTIVE (2026-01-01)\nID: W-001\n");
  w("docs/decisions.md", "## D-001 — Pick it — 2026-01-01\nWS: WS-01\nStatus: accepted\nPromote: yes (ADR-001)\n");
  commit("docs: board\n\nRefs: W-001", "docs/workstreams.md", "docs/decisions.md");
  w("docs/adr/ADR-001-pick.md", "# ADR-001: Pick it\n- Status: Accepted\n");
  commit("docs(adr): add\n\nRefs: W-001, D-001", "docs/adr/ADR-001-pick.md");
  w("docs/adr/ADR-001-pick.md", "# ADR-001: Pick it\n- Status: Accepted\nmore\n");
  commit("docs(adr): amend\n\nRefs: ADR-001", "docs/adr/ADR-001-pick.md");
  w("x.txt", "x");
  commit("chore: human", "x.txt");
  const out = generate(root);
  assert.match(out, /^# Fugue — traceability index/);
  assert.match(out, /GENERATED by trace-index.mjs — do not edit/);
  assert.match(out, /1 workstreams, 1 ADRs, 1 decisions, 4 commits \(1 unlinked\)/);
  assert.match(out, /### ADR-001[\s\S]*Introduced by: `[0-9a-f]+` docs\(adr\): add[\s\S]*Amended by:\n  - `[0-9a-f]+` docs\(adr\): amend/);
  assert.match(out, /### W-001[\s\S]*\[D-001\]\(#d-001\)/);
  assert.match(out, /### D-001[\s\S]*\[ADR-001\]\(adr\/ADR-001-pick\.md\)/);
  writeFileSync(path.join(root, OUT), out);
  commit("docs(trace): regenerate", OUT);
  assert.equal(generate(root), out, "re-run after committing the index is byte-identical");
});
