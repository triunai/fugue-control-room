#!/usr/bin/env node
// Generates docs/traceability.md: bidirectional links between commits, workstreams (W), decisions (D) and ADRs.
// Source = `git log` of HEAD (the `Refs:` trailers) plus the docs AS COMMITTED AT HEAD (board, project log + archive,
// decisions, docs/adr). Reading blobs at HEAD makes the output a pure function of HEAD: uncommitted edits never leak in,
// and re-running on the same HEAD is byte-identical.
//
// A commit that touches ONLY docs/traceability.md is a regeneration commit and is left out of the index; otherwise the
// file could never be current (committing it would add a commit it does not list). Commit it alone: `npm run trace`,
// then `git commit -- docs/traceability.md`.
//
//   node scripts/spine/trace-index.mjs            write docs/traceability.md
//   node scripts/spine/trace-index.mjs --stdout   print instead of writing
//   node scripts/spine/trace-index.mjs --check    ADVISORY: warn if the committed file is stale; never writes, always exit 0
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const OUT = "docs/traceability.md";
const HEADER = "GENERATED by trace-index.mjs — do not edit";

// ---------- pure parsers ----------
const pad = (n) => String(n).padStart(3, "0");
/** Canonical id: W-5 / W-005 -> W-005, D-21 -> D-021, ADR-8 -> ADR-008. */
export function canon(id) {
  const m = /^(W|D|ADR)-(\d+)$/.exec(id);
  return m ? `${m[1]}-${pad(Number(m[2]))}` : id;
}
const ID_RE = /\b(?:W|D|ADR)-\d+\b/g;
/** Ids in free text, ranges `D-016..D-026` expanded, canonical, de-duplicated, sorted. */
export function idsIn(text) {
  const out = new Set();
  for (const m of text.matchAll(/\b(D|W|ADR)-(\d+)\.\.(?:\1-)?(\d+)\b/g)) {
    const [a, b] = [Number(m[2]), Number(m[3])];
    if (b >= a && b - a < 200) for (let i = a; i <= b; i++) out.add(`${m[1]}-${pad(i)}`);
  }
  for (const m of text.matchAll(ID_RE)) out.add(canon(m[0]));
  return [...out].sort(byId);
}
export function byId(a, b) {
  const [ka, na] = a.split("-"), [kb, nb] = b.split("-");
  return ka === kb ? Number(na) - Number(nb) : ka < kb ? -1 : 1;
}
export const refIds = (raw) => [...new Set(raw.split(/[,;\s]+/).filter((s) => /^(W|D|ADR)-\d+\.?$/.test(s)).map((s) => canon(s.replace(/\.$/, ""))))];
/** GitHub-style heading anchor. */
export const slug = (h) => h.trim().toLowerCase().replace(/[^\p{L}\p{N}\s_-]/gu, "").replace(/\s/g, "-");
const esc = (s) => s.replace(/\|/g, "\\|");

export function parseBoard(text) {
  const lines = text.split("\n"), out = [];
  for (let i = 0; i < lines.length; i++) {
    const idm = /^ID:\s*(W-\d+)\s*$/.exec(lines[i]);
    if (!idm || i < 1 || !/^### WS-\d+/.test(lines[i - 1])) continue;
    const h = lines[i - 1];
    const m = /^###\s+(WS-\d+)\s+—\s+(.*?)\s+—\s+(\S+\s+)?([A-Z][A-Z ]*?)\s+\((\d{4}-\d{2}-\d{2})\)\s*$/.exec(h);
    out.push({ id: canon(idm[1]), ws: h.match(/WS-\d+/)[0], title: m ? m[2] : h.replace(/^###\s+WS-\d+\s+—\s+/, ""), status: m ? m[4].trim() : "?", date: m ? m[5] : "" });
  }
  return out;
}

/** Project-log style entries (warm log or archive month): returns closed-thread entries and their facts. */
export function parseLog(text, file = "project-log.md") {
  const out = [];
  for (const block of text.split(/^(?=## )/m)) {
    const head = /^## (.+)$/m.exec(block);
    if (!head || !block.startsWith("## ")) continue;
    const closed = /^Closed:\s*(W-\d+)\s*(?:\((WS-\d+)\))?\s*(.*)$/m.exec(block);
    const shas = [...(/^Commits:\s*\n((?:- .*\n?)*)/m.exec(block)?.[1] || "").matchAll(/^- ([0-9a-f]{7,40})\b/gm)].map((m) => m[1]);
    const dec = /^Decisions:\s*(.*)$/m.exec(block)?.[1] || "";
    out.push({ heading: head[1], anchor: slug(head[1]), file, closed: closed ? canon(closed[1]) : null, title: closed ? closed[3].trim() : head[1], shas, ids: idsIn(dec) });
  }
  return out;
}

export function parseDecisions(text) {
  const tableAdr = new Map();
  for (const m of text.matchAll(/^\|\s*(D-\d+)\s*\|[^\n]*$/gm)) tableAdr.set(canon(m[1]), idsIn(m[0].replace(/^\|\s*D-\d+/, "")).filter((i) => i.startsWith("ADR-")));
  const out = [];
  for (const block of text.split(/^(?=## D-)/m)) {
    const m = /^## (D-\d+)\s+—\s+(.*?)(?:\s+—\s+(\d{4}-\d{2}-\d{2}))?\s*$/m.exec(block.split("\n")[0] || "");
    if (!m || !block.startsWith("## D-")) continue;
    const id = canon(m[1]);
    const prom = /^Promote:\s*(.*)$/m.exec(block)?.[1] || "";
    const adrs = [...new Set([...idsIn(prom).filter((i) => i.startsWith("ADR-")), ...(tableAdr.get(id) || [])])].sort(byId);
    const ws = (/^WS:\s*(.*)$/m.exec(block)?.[1] || "").match(/WS-\d+/g) || [];
    out.push({ id, title: m[2], date: m[3] || "", heading: block.split("\n")[0].slice(3), anchor: slug(block.split("\n")[0].slice(3)), status: (/^Status:\s*(.*)$/m.exec(block)?.[1] || "").replace(/\s*\(.*$/, ""), adrs, ws: ws.map((w) => canon(`W-${w.slice(3)}`)) });
  }
  return out;
}

export function parseAdr(file, text) {
  const id = canon(/^(ADR-\d+)/.exec(file)[1]);
  const t = /^#\s+ADR-\d+\s*[:—-]+\s*(.*)$/m.exec(text);
  const s = /^-?\s*Status:\s*(.*)$/mi.exec(text);
  return { id, file, title: t ? t[1].trim() : file, status: s ? s[1].trim() : "?" };
}

export function parseGitLog(raw) {
  const commits = [];
  for (const rec of raw.split("\x1e")) {
    if (!rec.trim()) continue;
    const [head, ...rest] = rec.split("\n");
    const f = head.split("\x1f");
    if (f.length < 5) continue;
    const files = rest.filter(Boolean).map((l) => { const [st, ...p] = l.split("\t"); return { status: st, path: p.join("\t") }; });
    commits.push({ sha: f[1], full: f[0], date: f[2], subject: f[3], refs: refIds(f[4]), files });
  }
  return commits;
}

// ---------- model ----------
export function build({ commits, board, logs, decisions, adrs, adrFirst }) {
  const sha = (c) => c.sha;
  const visible = commits.filter((c) => !(c.files.length && c.files.every((f) => f.path === OUT)));
  const byShaPrefix = (s) => visible.find((c) => c.full.startsWith(s) || s.startsWith(c.sha));
  const W = new Map();
  const wk = (id, o = {}) => { if (!W.has(id)) W.set(id, { id, title: "", status: "", open: false, entry: null, commits: new Set(), ids: new Set() }); return Object.assign(W.get(id), o); };
  for (const b of board) wk(b.id, { title: b.title, status: b.status, open: true });
  for (const e of logs.filter((l) => l.closed)) {
    const w = wk(e.closed, { title: e.title, status: "CLOSED", entry: e });
    for (const s of e.shas) { const c = byShaPrefix(s); if (c) w.commits.add(c.sha); }
    for (const i of e.ids) w.ids.add(i);
  }
  const D = new Map(decisions.map((d) => [d.id, { ...d, commits: new Set(), ws: new Set(d.ws) }]));
  const A = new Map(adrs.map((a) => [a.id, { ...a, commits: new Set(), amended: [], intro: null, ws: new Set(), ds: new Set() }]));
  for (const c of visible) for (const r of c.refs) if (r.startsWith("W-")) wk(r).commits.add(c.sha);
  for (const w of W.values()) for (const cs of w.commits) {
    const c = visible.find((x) => x.sha === cs);
    for (const r of c.refs) if (!r.startsWith("W-")) w.ids.add(r);
  }
  for (const c of visible) {
    const ws = c.refs.filter((r) => r.startsWith("W-"));
    for (const r of c.refs) {
      if (D.has(r)) { D.get(r).commits.add(c.sha); ws.forEach((w) => D.get(r).ws.add(w)); }
      if (A.has(r)) { A.get(r).commits.add(c.sha); ws.forEach((w) => A.get(r).ws.add(w)); }
    }
    for (const f of c.files) {
      const m = /^docs\/adr\/(ADR-\d+)-.*\.md$/.exec(f.path);
      const a = m && A.get(canon(m[1]));
      if (!a) continue;
      ws.forEach((w) => a.ws.add(w));
      if (f.status === "A" && !a.intro) a.intro = c.sha;
    }
  }
  // intro = oldest add (visible is newest-first, so the last add wins); amended = every other commit touching the file
  for (const a of A.values()) {
    const adds = visible.filter((c) => c.files.some((f) => f.path === `docs/adr/${a.file}` && f.status === "A"));
    a.intro = adds.length ? adds[adds.length - 1].sha : null;
    a.amended = visible.filter((c) => c.sha !== a.intro && c.files.some((f) => f.path === `docs/adr/${a.file}`)).map(sha).reverse();
    for (const d of D.values()) if (d.adrs.includes(a.id)) { a.ds.add(d.id); }
  }
  for (const e of logs.filter((l) => l.closed)) for (const i of e.ids) {
    if (A.has(i)) A.get(i).ws.add(e.closed);
    if (D.has(i)) D.get(i).ws.add(e.closed);
  }
  const listed = new Map(); // sha -> W ids whose log entry lists it (pre-gate history)
  for (const e of logs.filter((l) => l.closed)) for (const s of e.shas) { const c = byShaPrefix(s); if (c) listed.set(c.sha, [...(listed.get(c.sha) || []), e.closed]); }
  return { visible, W, D, A, listed };
}

// ---------- rendering ----------
export function render(m) {
  const { visible, W, D, A, listed } = m;
  const bySha = new Map(visible.map((c) => [c.sha, c]));
  const cl = (s) => { const c = bySha.get(s); return `\`${c.sha}\` ${esc(c.subject)} (${c.date})`; };
  const oldestFirst = (set) => [...set].map((s) => bySha.get(s)).filter(Boolean).sort((a, b) => visible.indexOf(b) - visible.indexOf(a)).map((c) => c.sha);
  const wLink = (id) => `[${id}](#${id.toLowerCase()})`;
  const dLink = (id) => `[${id}](#${id.toLowerCase()})`;
  const aLink = (id) => `[${id}](#${id.toLowerCase()})`;
  const idLink = (id) => (id.startsWith("W-") ? wLink(id) : id.startsWith("D-") ? (D.has(id) ? dLink(id) : id) : A.has(id) ? aLink(id) : id);
  const unlinked = visible.filter((c) => !c.refs.length);
  const wIds = [...W.keys()].sort(byId), dIds = [...D.keys()].sort(byId), aIds = [...A.keys()].sort(byId);
  const L = [];
  L.push("# Fugue — traceability index", "", `> ${HEADER}. Regenerate with \`npm run trace\`; commit the result on its own.`, ">", "> Links commits, workstreams (W), decisions (D) and ADRs, both ways. Source: `git log` of HEAD (`Refs:` trailers) and the docs as committed.", "> Rules and ids: [`hygiene.md`](../hygiene.md), board [`workstreams.md`](workstreams.md), [`project-log.md`](project-log.md), [`decisions.md`](decisions.md).", "");
  L.push(`Counts: ${wIds.length} workstreams, ${aIds.length} ADRs, ${dIds.length} decisions, ${visible.length} commits (${unlinked.length} unlinked). Newest commit indexed: ${visible[0] ? `\`${visible[0].sha}\`` : "none"}.`, "");
  L.push("## Workstreams", "");
  for (const id of wIds) {
    const w = W.get(id);
    L.push(`### ${id}`, "", `**${w.title || "(untitled)"}** — ${w.status || "?"}`);
    L.push(w.open ? "- Where: [board](workstreams.md)" : w.entry ? `- Where: [project log entry](${w.entry.file === "project-log.md" ? "project-log.md" : `archive/project-log/${w.entry.file}`}#${w.entry.anchor})` : "- Where: (not found)");
    const ids = [...w.ids].sort(byId);
    L.push(`- Decisions and ADRs: ${ids.length ? ids.map(idLink).join(", ") : "none"}`);
    const cs = oldestFirst(w.commits);
    L.push(`- Commits (${cs.length}):`);
    if (!cs.length) L.push("  - none yet");
    for (const s of cs) L.push(`  - ${cl(s)}`);
    L.push("");
  }
  L.push("## ADRs", "");
  for (const id of aIds) {
    const a = A.get(id);
    L.push(`### ${id}`, "", `**${a.title}** — ${a.status} — [\`${a.file}\`](adr/${a.file})`);
    L.push(`- Introduced by: ${a.intro ? cl(a.intro) : "not committed yet"}`);
    L.push(`- Amended by: ${a.amended.length ? "" : "none"}`);
    for (const s of a.amended) L.push(`  - ${cl(s)}`);
    const cites = oldestFirst(a.commits);
    L.push(`- Cited in commit Refs: ${cites.length ? "" : "none"}`);
    for (const s of cites) L.push(`  - ${cl(s)}`);
    L.push(`- Workstreams: ${a.ws.size ? [...a.ws].sort(byId).map(wLink).join(", ") : "none"}`);
    L.push(`- Decisions: ${a.ds.size ? [...a.ds].sort(byId).map(dLink).join(", ") : "none"}`, "");
  }
  L.push("## Decisions", "");
  for (const id of dIds) {
    const d = D.get(id);
    L.push(`### ${id}`, "", `**${esc(d.title)}** — ${d.status || "?"} — [decisions.md](decisions.md#${d.anchor})`);
    L.push(`- ADR: ${d.adrs.length ? d.adrs.map((a) => (A.has(a) ? `[${a}](adr/${A.get(a).file})` : a)).join(", ") : "none"}`);
    L.push(`- Workstreams: ${d.ws.size ? [...d.ws].sort(byId).map(wLink).join(", ") : "none"}`);
    const cs = oldestFirst(d.commits);
    L.push(`- Cited in commit Refs: ${cs.length ? "" : "none"}`);
    for (const s of cs) L.push(`  - ${cl(s)}`);
    L.push("");
  }
  L.push("## Commit to ids", "", "| Commit | Subject | Date | Ids |", "|---|---|---|---|");
  for (const c of visible.filter((c) => c.refs.length)) L.push(`| \`${c.sha}\` | ${esc(c.subject)} | ${c.date} | ${c.refs.map(idLink).join(", ")} |`);
  L.push("", "## Unlinked (pre-gate or human)", "", "Commits with no `Refs:` trailer. A project-log entry may still list them.", "");
  if (unlinked.length) { L.push("| Commit | Subject | Date | Listed in log entry |", "|---|---|---|---|"); for (const c of unlinked) L.push(`| \`${c.sha}\` | ${esc(c.subject)} | ${c.date} | ${(listed.get(c.sha) || []).map(wLink).join(", ") || "-"} |`); } else L.push("None.");
  L.push("");
  return L.map((l) => l.trimEnd()).join("\n");
}

// ---------- git I/O ----------
const run = (root, args) => execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 1 << 28, stdio: ["ignore", "pipe", "ignore"] });
const showAt = (root, p) => { try { return run(root, ["show", `HEAD:${p}`]); } catch { return ""; } };
const lsAt = (root, dir) => { try { return run(root, ["ls-tree", "--name-only", "HEAD", `${dir}/`]).split("\n").filter(Boolean).map((p) => p.slice(dir.length + 1)); } catch { return []; } };

export function collect(root) {
  const raw = run(root, ["log", "HEAD", "--date=short", "--name-status", "--no-renames", "--format=%x1e%H%x1f%h%x1f%ad%x1f%s%x1f%(trailers:key=Refs,valueonly,separator=%x2C)"]);
  const logs = [...parseLog(showAt(root, "docs/project-log.md"), "project-log.md"),
    ...lsAt(root, "docs/archive/project-log").filter((f) => /^\d{4}-\d{2}\.md$/.test(f)).sort().reverse().flatMap((f) => parseLog(showAt(root, `docs/archive/project-log/${f}`), f))];
  const adrs = lsAt(root, "docs/adr").filter((f) => /^ADR-\d+-.*\.md$/.test(f)).sort().map((f) => parseAdr(f, showAt(root, `docs/adr/${f}`)));
  return { commits: parseGitLog(raw), board: parseBoard(showAt(root, "docs/workstreams.md")), logs, decisions: parseDecisions(showAt(root, "docs/decisions.md")), adrs };
}
export const generate = (root) => render(build(collect(root)));

function main(argv) {
  const root = process.cwd();
  let text;
  try { text = generate(root); } catch (e) { console.error(`trace-index: ${e.message}`); process.exit(argv.includes("--check") ? 0 : 1); }
  if (argv.includes("--stdout")) { process.stdout.write(text); return; }
  const file = path.join(root, OUT);
  if (argv.includes("--check")) {
    const cur = existsSync(file) ? readFileSync(file, "utf8") : null;
    if (cur !== text) console.warn(`trace-index: ${OUT} is ${cur === null ? "missing" : "stale"}; run \`npm run trace\` and commit it alone (advisory, not blocking).`);
    else console.log("trace-index: up to date");
    return;
  }
  writeFileSync(file, text);
  console.log(`trace-index: wrote ${OUT}`);
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main(process.argv.slice(2));
